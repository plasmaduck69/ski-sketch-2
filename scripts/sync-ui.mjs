// Builds the lab page from the single-source UI (ui/lab.html) and engine (lib/engine.js).
// The same lab.html is what the hosted Claude artifact runs. Here it is wrapped in a full HTML
// shell and served by app/lab/route.ts only to signed-in users, with a config flag that points
// saving and the optimizer at this app's API. engine.js and the icon are public static files.
import { mkdirSync, readFileSync, writeFileSync, copyFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const pub = join(root, "public", "lab");
const gen = join(root, "generated");
mkdirSync(pub, { recursive: true });
mkdirSync(gen, { recursive: true });

// The page's module imports ("./engine.js", "./sheet-ui.js") become absolute /lab/ paths,
// because the page itself is served at /lab.
const body = readFileSync(join(root, "ui", "lab.html"), "utf8").replaceAll('from "./', 'from "/lab/');
if (!body.includes('from "/lab/engine.js"')) throw new Error("sync-ui: couldn't find the engine import in ui/lab.html");
const html = `<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width,initial-scale=1,viewport-fit=cover">
<link rel="icon" href="/lab/icon.svg" type="image/svg+xml">
<script>window.SKI_LAB_CONFIG = __SKI_LAB_CONFIG__;</script>
</head>
<body>
${body}
</body>
</html>
`;
writeFileSync(join(gen, "lab-page.ts"), "// Generated by scripts/sync-ui.mjs from ui/lab.html. Do not edit.\nexport default " + JSON.stringify(html) + ";\n");
const modules = ["engine.js", "sheet.js", "sheet-data.js", "sheet-ui.js", "models.js"];
for (const m of modules) copyFileSync(join(root, "lib", m), join(pub, m));
copyFileSync(join(root, "ui", "icon.svg"), join(pub, "icon.svg"));
console.log(`sync-ui: wrote generated/lab-page.ts and public/lab/{${modules.join(",")},icon.svg}`);
